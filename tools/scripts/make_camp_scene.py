    s.mesh(prop["lantern_glass"], mat["glass_warm"])

    # A second, much smaller pool of light. Two sources at very different
    # strengths is what stops a night scene reading as a single spotlight in a
    # void, and it costs one point light with a three metre reach.
    s.entity("Lantern Light", parent="Lantern", position=(0, 0.15, 0))
    s.block("LightComponent", [
        ("Type", "Point"), ("Color", "[1, 0.82, 0.5]"), ("Intensity", 1.1),
        ("Range", 3.2), ("InnerCone", 20), ("OuterCone", 30),
    ])

    # Toasting forks, reaching into the fire. Leading lines, and the detail
    # that says somebody is sitting here rather than that somebody left.
    for i, (x, z, yaw) in enumerate(((-1.18, 1.02, 130.8), (-0.88, 1.32, 138.0))):
        s.entity(f"Fork {i}", position=(x, ground_height(x, z) + 0.30, z),
                 rotation=(math.radians(6.0), math.radians(yaw), 0))
        s.mesh(prop["fork"], mat["metal"])

        s.entity(f"Marshmallow {i}", parent=f"Fork {i}", position=(0, 0.05, 0.78))
        s.mesh(prop["marshmallow"], mat["white"])

    # --- who is here ---------------------------------------------------------
    #
    # The fox at the edge of the firelight, turned in. The only thing in the
    # scene that is alive, and the whole of the skinning story.
    s.entity("Fox", position=(4.15, ground_height(4.15, 1.95), 1.95),
             rotation=(0, math.radians(-148), 0), scale=(0.009, 0.009, 0.009))
    s.mesh(MESH_FOX, MAT_FOX)
    s.block("AnimatorComponent", [
        # **1.0 -- the clip at the rate it was authored at.** Slowing it read
        # as "calm" in a still and as "stuck" in motion, and the same
        # compounding that got the camera got this: 0.55, then 0.28, then
        # 0.14, each a fraction of the last.
        ("Clip", 0), ("Playing", "true"), ("Loop", "true"), ("Speed", 1.0),
        ("BlendTime", 0.4),
    ])

    # And the name tag over its head. The engine's UI is screen space -- a
    # canvas has a scale mode and no world mode -- so a label belonging to
    # something *in* the scene has to be geometry: a quad wearing a plaque
    # texture, turned to face the camera by `Billboard`. It is lit by the fire,
    # occluded by the tent and reflected in the mirror like anything else,
    # which a screen-space label would not be.
    #
    # The height is the fox's own: about 0.9 m at this scale, and the tag sits
    # a little clear of the ears rather than on them.
    s.entity("Foxy Label",
             position=(4.15, ground_height(4.15, 1.95) + 0.98, 1.95),
             # 42 cm across, which is a third smaller than it first was. A tag
             # wider than the animal it names stops being a label and becomes
             # a sign the animal is standing next to.
             scale=(0.42, 0.158, 1.0))
    s.mesh(QUAD, mat["nameplate"])
    s.managed_script("Billboard")

    # And the rabbits, which are what make the camp feel visited rather than
    # staged. Three, all facing the fire, at the distance an animal actually
    # stops at.
    for i, (x, z, yaw) in enumerate(((1.62, 1.08, -2.15), (2.02, 1.42, -2.42),
                                     (1.26, 1.62, -1.75))):
        s.entity(f"Rabbit {i}", position=(x, ground_height(x, z), z),
                 rotation=(0, yaw, 0))
        s.mesh(prop["rabbit"], mat["fur"])

    # --- the forest ----------------------------------------------------------
    #
    # Rings of pines around the clearing, sparser as they go out so the
    # treeline has depth rather than being a fence. Four tree shapes rather
    # than one at three sizes -- a forest of one silhouette reads as a texture.
    #
    # Canopy and trunk are separate entities because one FBX carries one
    # material, and a green trunk is the detail that gives a low-poly tree away.
    s.entity("Forest")

    corridor = camera_corridor()

    def clear_of_camera(x, z, margin):
        """True if a tree here is out of the camera's way -- and the van's.

        `margin` is the tree's **own canopy radius** plus clearance, not a
        tuned constant. A fixed margin cannot be right for a prop that ships in
        four shapes and is then scaled between 0.78 and 1.33: the number that
        clears a 1.05 m sapling puts the lens inside a 2.6 m pine, which is
        what the camera was flying through.
        """
        # The van is 4.5 m long and sits at a fixed spot, so it gets the same
        # treatment as the camera: the scenery gives way to the things that
        # were placed on purpose.
        if math.hypot(x - VAN_AT[0], z - VAN_AT[1]) < 3.8:
            return False

        for i, point in enumerate(corridor):
            if math.hypot(x - point[0], z - point[1]) < margin:
                return False
            if i + 1 < len(corridor):
                # The travel between two shots as well as the shots
                # themselves -- a tree the camera flies through is worse than
                # one it merely ends up inside, because it flashes.
                # **The full margin, not three quarters of it.** A tree the
                # camera flies through is worse than one it merely ends up
                # inside, because it flashes -- so allowing the travel nearer
                # than the shot is exactly backwards.
                if segment_distance((x, z), point, corridor[i + 1]) < margin:
                    return False
        return True

    def plant(label, kind, x, z, spin, size, surface, trunk_scale=1.0):
        y = ground_height(x, z)
        s.entity(label, parent="Forest", position=(x, y, z),
                 rotation=(0, spin, 0), scale=(size, size * 1.04, size))
        s.mesh(prop[kind], mat[surface])

        s.entity(label + " Trunk", parent=label,
                 scale=(trunk_scale, trunk_scale, trunk_scale))
        s.mesh(prop["pine_trunk"], mat["bark"])

    shapes = ("pine", "pine_tall", "pine_wide", "pine")

    # Each shape's widest tier, from the model. The camera needs to clear this
    # plus its near clip and a little more, or it ends up looking at the inside
    # of a facet.
    canopy = {"pine": 1.55, "pine_tall": 1.35, "pine_wide": 1.95,
              "pine_small": 1.05}
    # The canopy radius is the widest tier's, and a camera passing a tree has a
    # near clip plane and a frame of its own. Two metres on top is what keeps a
    # skirt out of the corner of shot.
    CLEARANCE = 2.2

    for i, (x, z, spin, size) in enumerate(scatter(3, 58, 9.0, 26.0)):
        kind = shapes[i % len(shapes)]
        if not clear_of_camera(x, z, canopy[kind] * size + CLEARANCE):
            continue
        plant(f"Pine {i}", kind, x, z, spin, size, "needle_far",
              trunk_scale=1.15)

    for i, (x, z, spin, size) in enumerate(scatter(7, 38, 6.4, 15.0)):
        kind = shapes[(i + 2) % len(shapes)]
        if not clear_of_camera(x, z, canopy[kind] * size * 0.9 + CLEARANCE):
            continue
        plant(f"Pine Near {i}", kind, x, z, spin, size * 0.9, "needle")

    for i, (x, z, spin, size) in enumerate(scatter(13, 34, 4.8, 12.0)):
        if not clear_of_camera(x, z, canopy["pine_small"] * size + CLEARANCE):
            continue
        plant(f"Sapling {i}", "pine_small", x, z, spin, size, "needle",
              trunk_scale=0.8)

    # The frame's own edges. Five big trees placed by hand rather than
    # scattered, because framing is a decision about the *picture* and a random
    # ring will not make it -- these are the ones the establishing shot looks
    # past, nearer and darker than everything behind them.
    for i, (x, z, size) in enumerate(((-9.6, 8.8, 1.4), (10.6, 7.6, 1.3),
                                      (-9.6, 1.1, 1.15), (9.4, -4.2, 1.2),
                                      (-4.0, 11.6, 1.3))):
        kind = "pine_tall" if i % 2 else "pine"
        if not clear_of_camera(x, z, canopy[kind] * size + CLEARANCE):
            raise SystemExit(
                f"Frame Pine {i} at ({x}, {z}) is in the camera's way. These "
                "five are placed by hand for the composition, so this is a "
                "decision to revisit rather than a tree to drop.")
        plant(f"Frame Pine {i}", kind, x, z, i * 1.7, size, "needle",
              trunk_scale=1.2)

    # --- the ground cover ----------------------------------------------------
    #
    # Tufts and stones, scattered thickly. **These are not decoration.** In the
    # reference they are most of why the ground reads as somewhere rather than
    # as a floor -- there are a great many of them, they are small, and the
    # grass is the brightest colour in the frame after the fire.
    s.entity("Scatter")

    tufts = (("grass", 29, 190), ("grass_tall", 31, 130), ("grass_low", 37, 150))
    for kind, seed, count in tufts:
        for i, (x, z, spin, size) in enumerate(scatter(seed, count, 1.15, 15.0)):
            s.entity(f"Tuft {kind} {i}", parent="Scatter",
                     position=(x, ground_height(x, z) - 0.02, z),
                     rotation=(0, spin, 0),
                     # Half size. At full size a tuft stood higher than the
                     # stump next to it -- in the reference they come about a
                     # third of the way up a chair leg, and they are the
                     # brightest thing in the frame after the fire, so getting
                     # them too big costs the fire its focus as well.
                     scale=(size * 0.5, size * 0.55, size * 0.5))
            s.mesh(prop[kind], mat["blade"])

    for i, (x, z, spin, size) in enumerate(scatter(41, 210, 0.95, 13.0)):
        s.entity(f"Pebble {i}", parent="Scatter",
                 position=(x, ground_height(x, z) - 0.02, z),
                 rotation=(0, spin, 0), scale=(size, size * 0.8, size))
        s.mesh(prop["pebble"], mat["stone_dark"])

    stones = (("rock", 43, 14), ("rock_flat", 47, 12), ("rock_tall", 53, 8))
    for kind, seed, count in stones:
        for i, (x, z, spin, size) in enumerate(scatter(seed, count, 2.6, 15.0)):
            s.entity(f"Stone {kind} {i}", parent="Scatter",
                     position=(x, ground_height(x, z) - 0.06, z),
                     rotation=(0, spin, 0),
                     scale=(size * 0.8, size * 0.7, size * 0.8))
            s.mesh(prop[kind], mat["stone_dark"])

    # --- the night -----------------------------------------------------------
    #
    # One dim directional light standing in for the moon: enough to separate
    # the trees from the sky and give the ground a direction, and nowhere near
    # enough to compete with the fire. A night scene lit only by its fire is a
    # black rectangle with an orange dot in it.
    s.entity("Moon", rotation=(math.radians(-124), math.radians(31), 0))
    s.block("LightComponent", [
        # Its whole job is the *edge* of the trees against the sky.
        ("Type", "Directional"), ("Color", "[0.4, 0.52, 0.85]"),
        ("Intensity", 0.06), ("Range", 60), ("InnerCone", 20),
        ("OuterCone", 30),
    ])

    # The last of the sunset, behind the treeline and low. The reference has a
    # warm glow between the far trunks and it is doing something specific: it
