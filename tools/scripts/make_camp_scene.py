def write_curve(path, channels, keys):
    """A `.rcurve` and its sidecar.

    The camp's flame has a shape of its own: it swells fast, holds, and thins
    out. The courtyard's curves describe a brazier, and borrowing them would be
    the same recycling this scene is not doing anywhere else.
    """
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines = [f"Curve: {channels}", "Keys:"]
    for time, values in keys:
        lines.append(f"  - T: {time:g}")
        lines.append("    V: [" + ", ".join(f"{v:g}" for v in values) + "]")
    path.write_text(chr(10).join(lines) + chr(10), encoding="utf-8")

    handle = postprofile.profile_handle(path.name)
    path.with_name(path.name + ".meta").write_text(
        f"Handle: {handle}\nType: Curve\n"
        f"SourceHash: {postprofile.source_hash(path)}\n", encoding="utf-8")
    return handle


def materials(tex):
    """Every surface the camp wears, over the camp's own maps.

    **Tiling is a property of the surface, not of the texture.** The props
    carry planar UVs scaled at export, so one tile here is roughly one prop --
    which is what a flat-patch map wants, since the point of it is that a
    handful of facets fall across the object rather than a thousand.
    """
    directory = ASSETS / "materials"

    def surface(name, colour, base, **kwargs):
        maps = {"BaseColor": tex[colour]} if colour else {}
        return write_material(directory / f"camp_{name}.rmat", maps,
                              tiling=kwargs.pop("tiling", (1, 1)),
                              base_color=base, **kwargs)

    return {
        # The clearing floor and the scrub on the rises. The terrain's own
        # TextureScale multiplies these, so the tiling here stays at one.
        # Warm soil brown, not the slate it used to be. The fire is the only
        # warm light in the frame, and a ground that is already cold gives it
        # nothing to warm.
        # Warm, and **dark**. Warm because the fire is the only warm light and
        # a cold ground gives it nothing to warm; dark because the firelight
        # has to be visible *as a pool*, and a ground that is already a mid
        # value everywhere has no room for one.
        "ground": surface("ground", "ground", (0.42, 0.31, 0.22, 1),
                          roughness=0.96, height_scale=0.015),
        "scrub": surface("scrub", "ground", (0.40, 0.40, 0.24, 1),
                         roughness=0.96, height_scale=0.01),

        # Two greens for the canopy, and the difference between them is
        # deliberate: the far ring is darker and bluer, which is the only
        # aerial perspective a scene twenty metres deep can have.
        "needle": surface("needle", "needle", (0.11, 0.28, 0.24, 1),
                          roughness=0.94),
        "needle_far": surface("needle_far", "needle", (0.07, 0.19, 0.20, 1),
                              roughness=0.95),
        "bark": surface("bark", "bark", (0.33, 0.22, 0.16, 1), roughness=0.95),
        "wood": surface("wood", "bark", (0.47, 0.33, 0.22, 1), roughness=0.9),
        # What has been in a fire. Nearly black, and it is what makes the flame
        # above it look hot -- a bright log under a bright flame is a bonfire
        # with no contrast in it.
        "charred": surface("charred", "bark", (0.10, 0.08, 0.08, 1),
                           roughness=0.98),

        "stone": surface("stone", "stone", (0.62, 0.60, 0.60, 1), roughness=0.85),
        "stone_dark": surface("stone_dark", "stone", (0.30, 0.31, 0.38, 1),
                              roughness=0.88),
        "blade": surface("blade", "needle", (0.30, 0.68, 0.20, 1), roughness=0.9),

        "canvas_red": surface("canvas", "canvas", (0.76, 0.13, 0.15, 1),
                              roughness=0.86),
        "canvas_pale": surface("canvas_pale", "canvas", (0.94, 0.92, 0.88, 1),
                               roughness=0.86),
        "shadow": surface("shadow", None, (0.02, 0.02, 0.03, 1), roughness=1.0),
        "rope": surface("rope", "fabric", (0.46, 0.41, 0.33, 1), roughness=0.95),

        # **Emissive above one, and that is the point of the field.** A flame
        # has to survive a tone mapper compressing everything near white; a
        # surface that emits exactly white comes out grey, and a grey flame is
        # the single fastest way to make a night scene look wrong.
        # Backed off from 5.5 and 8.0. Close up -- shot 3 is two metres from
        # the fire -- the flame was clipping to a flat yellow shape with no
        # facets left in it, which loses the one thing that made modelling it
        # rather than emitting particles worth doing.
        "flame_hot": surface("flame_hot", None, (1.0, 0.42, 0.08, 1),
                             roughness=1.0, emissive=(3.8, 1.15, 0.22, 1)),
        "flame_core": surface("flame_core", None, (1.0, 0.88, 0.42, 1),
                              roughness=1.0, emissive=(5.4, 3.3, 0.95, 1)),

        "metal": surface("metal", "metal", (0.09, 0.09, 0.11, 1),
                         metallic=0.7, roughness=0.42),
        "fabric_blue": surface("fabric_blue", "fabric", (0.15, 0.20, 0.52, 1),
                               roughness=0.92),
        "fabric_red": surface("fabric_red", "fabric", (0.66, 0.15, 0.16, 1),
                              roughness=0.92),
        "fabric_dark": surface("fabric_dark", "fabric", (0.16, 0.15, 0.19, 1),
                               roughness=0.94),
        "leather": surface("leather", "bark", (0.43, 0.28, 0.16, 1),
                           roughness=0.7),
        "plastic": surface("plastic", "fabric", (0.78, 0.80, 0.83, 1),
                           roughness=0.55),
        "enamel": surface("enamel", "fabric", (0.86, 0.88, 0.9, 1),
                          roughness=0.4),
        "white": surface("white", None, (0.96, 0.93, 0.86, 1), roughness=0.85),

        # The name tag. A modest flat emissive so the sign is readable four
        # metres from the fire without being a lamp -- and the letters stay
        # dark because they are dark in the *map*, which is the only way to
        # have a partly-glowing surface with no emissive map to vary it.
        "nameplate": surface("nameplate", "foxy", (1.0, 1.0, 1.0, 1),
                             roughness=0.85, emissive=(0.34, 0.3, 0.24, 1)),

        # The van. Pale green paint, because the frame already has a red tent
        # in it and a second saturated body colour would fight it for the eye;
        # a muted one reads as a vehicle and stays out of the way.
        # Dark, not pale. At two-thirds white the van was the brightest large
        # object in a night frame and pulled the eye off the fire, which is the
        # one thing this composition cannot afford.
        # **Light enough to read as a vehicle.** At a third of white the van
        # was a dark grey box in a dark frame and looked like a shipping
        # container -- no windows, no wheels, no roof line, because none of
        # them had any value to differ by. The paint has to be well above the
        # glass and the tyres or the shape has nothing in it.
        #
        # Still muted: the frame already has a red tent for its saturated
        # colour, and a second one would fight it.
        "paint": surface("paint", "metal", (0.54, 0.58, 0.51, 1),
                         metallic=0.35, roughness=0.45),
        "glass_dark": surface("glass_dark", None, (0.05, 0.07, 0.10, 1),
                              metallic=0.2, roughness=0.12),
        "rubber": surface("rubber", "metal", (0.06, 0.06, 0.07, 1),
                          roughness=0.9),
        "fur": surface("fur", "fabric", (0.38, 0.32, 0.29, 1), roughness=0.95),
        "glass_warm": surface("lantern_glass", None, (1.0, 0.9, 0.62, 1),
                              roughness=0.3, emissive=(3.0, 2.1, 0.9, 1)),

        # The glass. Metal at almost zero roughness, which is what a mirror
        # *is* -- silvered glass is a metal surface with a pane in front of it,
        # and modelling the pane separately would buy a refraction this
        # renderer does not do.
        #
        # Not pure white: a real mirror returns about 95 % and a perfect one
        # looks wrong beside surfaces that do not.
        "mirror": surface("mirror", None, (0.95, 0.96, 0.97, 1),
                          metallic=1.0, roughness=0.03),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(ASSETS / "scenes" / "camp.rage"))
    args = parser.parse_args()

    prop = handles_in(ASSETS / "models" / "camp", ".fbx", "")
    require(prop, "pine", "pine_tall", "pine_wide", "pine_small", "pine_trunk",
            "tent", "tent_band", "tent_door", "guy_line", "flame_outer",
            "flame_inner", "fire_logs", "firewood", "log_split", "chair_frame",
            "chair_seat", "log", "stump", "rock", "rock_flat", "rock_tall",
            "pebble", "grass", "grass_tall", "grass_low", "pack", "bedroll",
            "suitcase", "cooler", "lantern", "lantern_glass", "pot", "mug",
            "fork", "marshmallow", "mirror_frame", "mirror_glass", "rabbit",
            "van_body", "van_glass", "van_wheels")

    tex = handles_in(ASSETS / "materials", "_color.png", "camp_")
    tex.update({
        "flame": read_handle(ASSETS / "textures" / "camp_flame.png.meta"),
        "spark": read_handle(ASSETS / "textures" / "camp_spark.png.meta"),
        "foxy": read_handle(ASSETS / "textures" / "camp_foxy.png.meta"),
        "lut": read_handle(ASSETS / "post" / "camp.rvlut.meta"),
        "terrain": read_handle(ASSETS / "terrain" / "clearing.rvterrain.meta"),
        "fire_sound": read_handle(ASSETS / "audio" / "camp_fire.wav.meta"),
        "ambience": read_handle(ASSETS / "audio" / "camp_night.wav.meta"),
        "font": read_handle(ASSETS / "fonts" / "roboto.rvfont.meta"),
    })
    require(tex, "ground", "bark", "canvas", "fabric", "stone", "needle",
            "metal", "flame", "spark", "lut", "terrain", "fire_sound",
            "ambience", "font", "foxy")

    curves = ASSETS / "curves"
    curve = {
        # A tongue of flame is widest a third of the way up and narrows again
        # as it burns out. Two endpoints can only widen or only narrow, so this
        # is the shape a start/end pair cannot hold.
        "size": write_curve(curves / "camp_flame_size.rcurve", 1,
                            ((0.0, [0.28]), (0.28, [0.9]), (0.62, [0.58]),
                             (1.0, [0.12]))),
        # An ember has no hard edge at either end: it appears out of nothing
        # and thins out rather than being switched off.
        "alpha": write_curve(curves / "camp_flame_alpha.rcurve", 1,
                             ((0.0, [0.0]), (0.1, [1.0]), (0.5, [0.65]),
                              (1.0, [0.0]))),
        # Through orange on the way from yellow to a dark red, which a straight
        # crossfade would cut the corner of -- and cutting that corner is
        # exactly what makes a fire look like a light bulb.
        "ember": write_curve(curves / "camp_ember.rcurve", 3,
                             ((0.0, [1.0, 0.94, 0.6]), (0.3, [1.0, 0.52, 0.14]),
                              (0.72, [0.68, 0.15, 0.04]),
                              (1.0, [0.2, 0.03, 0.02]))),
    }

    mat = materials(tex)

    # Night, and every effect chosen for the picture.
    settings = {
        # **Fixed, not automatic.** Auto exposure hunts for a mid-grey and
        # finds one in any scene, so a night scene comes back correctly exposed
        # and therefore not night. The fire is the subject; it should be the
        # only thing near white in the frame.
        "Exposure": 0.78,
        "AutoExposure": False,

        "BloomEnabled": True,
        # Above the lit ground, so only the flame blooms. Below it, bloom
        # spreads the firelight over the whole clearing and undoes the falloff
        # the light was tuned for.
        "BloomThreshold": 1.45,
        "BloomKnee": 0.4,
        "BloomIntensity": 0.075,
        "BloomClamp": 14.0,

        # **The depth of field is most of why the reference reads as a
        # miniature**, and it is not subtle there: the foreground trees and the
        # treeline are both well out of focus and only the camp is sharp.
        "DepthOfField": True,
        # **One focus distance has to serve twelve shots**, and they range from
        # 2.3 m (the mirror, close) to 9.6 m (the final wide). At 7.2 m and
        # f/1.45 the establishing shot was beautiful and the fox -- the subject
        # of the shot that closes the film -- was a soft orange smear, along
        # with its name tag. Five metres and f/2 keeps the near shots readable
        # and still throws the treeline out on the wides, which is where the
        # miniature effect actually comes from.
        #
        # A focus distance per shot would be better and is not available: the
        # profile is an asset the camera points at, not a field a script can
        # set.
        # Overridden per band below; the value here is the fallback for
        # anything that reads this dict directly.
        "FocusDistance": 5.4,
        "FocalLength": 55.0,
        # Back to a shallow stop now that each shot focuses on its own subject.
        # The shallow depth is most of why the reference reads as a miniature,
        # and it was only stopped down to paper over one focus serving twelve
        # shots.
        "Aperture": 1.8,
        "MaxBokehRadius": 14.0,

        # **Screen-space reflections, and the mirror is what they are for.**
        # Between them the probe, the screen-space pass and the traced pass are
        # three different answers to the same question, and the mirror is the
        # one surface in the scene where you can see them disagree: the probe
        # supplies what a cubemap taken at the glass sees, SSR corrects it with
        # what is actually on screen, and tracing adds what is behind the
        # camera. Turning any of them off is visible in that one rectangle.
        "ScreenSpaceReflections": True,
        "SsrMaxDistance": 26.0,
        "SsrThickness": 0.4,
        "SsrIntensity": 1.0,

        "AmbientOcclusion": True,
        "AoRadius": 0.5,
        "AoIntensity": 0.85,

        "GlobalIllumination": True,
        "GiRadius": 2.5,
        "GiQuality": "Low",
        # **0.4, not 1.1.** With the project's ray-traced GI switched on as
        # well, indirect light at full strength lifts the whole clearing to an
        # even dusk: the ground away from the fire stops being dark, the
        # falloff the fire's range was tuned for disappears, and the scene
        # reads as an overcast afternoon with an orange prop in it. Bounce
        # light is worth having here for the warm spill onto the chairs and the
        # tent, and that is all it is worth having for.
        "GiIntensity": 0.4,
        # One bounce. The fire is the only bright thing here, so a second
        # bounce spends its time carrying almost nothing into the dark.
        "GiBounces": 1,
        "GiDenoise": 0.9,

        # Voxel GI as well, because the fire is a *local* source in a scene
        # with no sky light to speak of -- and the warm bounce off the ground
        # onto the chairs and the tent is a good part of why a campfire reads
        # as one. A screen-space method alone loses it the moment the ground
        # leaves the frame.
        "VoxelGlobalIllumination": True,
        "VoxelGiResolution": 128,
        "VoxelGiCascades": 2,
        "VoxelGiVoxelSize": 0.22,

        "MotionBlur": True,
        "MotionBlurShutter": 0.4,
        # The camera moves slowly and the blur should stay a smear rather than
        # becoming a comet: capped well below the default.
        "MotionBlurMaxRadius": 8.0,

        "ColorLut": tex["lut"],
        "ColorLutStrength": 0.85,

        "VignetteIntensity": 0.44,
        "VignetteSmoothness": 0.7,
        "ChromaticAberration": 0.0011,
        # Low. The reference is a rendered poster, not film -- grain is the one
        # effect that makes a clean low-poly image look like a photograph of a
        # screen. Enough to keep the dark parts from banding and no more.
        "FilmGrain": 0.07,
        "FilmGrainSize": 1.5,
    }

    # One profile per focus band, identical in every other respect. The camp's
    # own `camp.rvpostprofile` stays as the mid band under its old name, so a
    # camera that has not been told otherwise still grades the scene correctly.
    profiles = {}
    profile_paths = {}
    for band in FOCUS_BANDS:
        name = ("camp.rvpostprofile" if band == 5.4
                else "camp_focus_{0}.rvpostprofile".format(
                    str(band).replace(".", "_")))
        profiles[band] = postprofile.write_named(
            ASSETS / "post" / name, dict(settings, FocusDistance=band))
        # What the asset registry will call this file: relative to the asset
        # directory, forward slashes, which is what GetHandle matches on.
        profile_paths[band] = "post/" + name

    scene = build(profiles, profile_paths, mat, prop, tex, curve)

    header = [
        "Scene: Camp",
        # **Without this the loader throws every EntityID away.** A file with
        # no Version is version 1, and version 1 wrote the same hardcoded id
        # for every entity -- so the reader mints fresh ids instead of
        # honouring what is on disk. The entities still load and the scene
        # still renders, and then every single parent reference resolves to
        # nothing: the tent's pale band and its doorway sat on the campfire
        # three metres from the tent, every chair lost its seat, and a hundred
        # tree trunks stacked up on the origin in one brown column.
        f"Version: {SCENE_VERSION}",
        "Environment:",
        "  Ambient: [0.028, 0.03, 0.055]",
        "  AmbientIntensity: 1",
        # **A gradient, not a panorama.** A cubemap sky is the scene's
        # image-based light as well as its backdrop, so a dusk HDR lights every
        # surface in the clearing with dusk -- which is exactly what the trees
        # came back as, and turning the moon down could never have fixed it,
        # because the moon was not what was lighting them.
        #
        # Nearly black, with the last of the sunset left in the horizon band.
        "  Sky: Gradient",
        "  SkyHorizon: [0.10, 0.07, 0.11]",
        "  SkyZenith: [0.014, 0.018, 0.048]",
        "  SkyGround: [0.008, 0.01, 0.018]",
        "  SkyIntensity: 1",
        "  SkyRotation: 0",
        "Entities:",
    ]

    path = pathlib.Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(chr(10).join(header) + chr(10) + scene + chr(10),
                    encoding="utf-8")

    entities = scene.count("  - EntityID:")
    print(f"{path}: {entities} entities")
    print(f"  {len(prop)} props, {len(mat)} materials, {len(curve)} curves")
    print(f"  focus     " + ", ".join(
        f"{name}@{focus_band(distance):g}m"
        for name, _, distance, _, _ in SHOTS))
    for name, target, distance, yaw, pitch in SHOTS:
        position, _ = look_at(target, distance, yaw, pitch)
        print(f"  {name}    at ({position[0]:.2f}, {position[1]:.2f}, "
              f"{position[2]:.2f})  looking at {target}")


if __name__ == "__main__":
    main()
