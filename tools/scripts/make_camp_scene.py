# **One focus distance cannot serve twelve shots.** They range from 2.3 m -- the
# mirror, close -- to 9.6 m at the final wide, and a single value leaves either
# the close shots blurred at the front or the wides blurred at the subject. The
# fox's own closing shot came back as a soft orange smear with an unreadable
# name tag, which is the shot the whole film ends on.
#
# So the camera changes focus per shot, and **the script carries the table**:
# one field on CampCamera holding the profile each shot wants, in shot order,
# written here so the two cannot drift.
#
# It used to be a CameraComponent on every marker, ViewRank 90 so none of them
# could ever become primary, and the script read each marker's profile off it.
# That worked and it cost the scene twelve cameras to hold twelve numbers --
# a whole component, with a projection and clip planes and an aspect flag, per
# marker, none of which was ever rendered through. A scene that reports
# thirteen cameras when it has one is a scene that is lying about itself.
#
# Four bands rather than twelve profiles: focus is a soft quantity and the
# difference between 3.4 m and 3.6 m is not visible, while four small files are
# four things to keep track of instead of twelve.
FOCUS_BANDS = (2.6, 3.6, 5.4, 8.4)


def focus_band(distance):
    """The band nearest a subject distance."""
    return min(FOCUS_BANDS, key=lambda band: abs(band - distance))


def segment_distance(point, a, b):
    """Distance from a point to a line segment, in the ground plane."""
    ax, az = a
    bx, bz = b
    dx, dz = bx - ax, bz - az
    length = dx * dx + dz * dz
    if length < 1e-9:
        return math.hypot(point[0] - ax, point[1] - az)

    t = ((point[0] - ax) * dx + (point[1] - az) * dz) / length
    t = min(max(t, 0.0), 1.0)
    return math.hypot(point[0] - (ax + dx * t), point[1] - (az + dz * t))


def camera_corridor():
    """Where the camera goes, as a chain of ground-plane points.

    **A scattered forest will put a tree where the camera stands**, and the
    establishing shot came back as one enormous out-of-focus green facet
    because of it. The camera is nine metres out and the tree rings start at
    five, so this was not bad luck -- it was certain.

    Trees are rejected against this rather than the camera being moved to
    wherever the trees happen not to be, because the shots are the composition
    and the forest is scenery. The scenery gives way.
    """
    path = []
    for _, target, distance, yaw, pitch in SHOTS:
        position, _ = look_at(target, distance, yaw, pitch)
        path.append((position[0], position[2]))
    return path


def look_at(target, distance, yaw, pitch):
    """Where the camera stands to hold `target` in the middle of frame.

    Zero rotation looks down -Z, so forward is
    (-sin yaw cos pitch, sin pitch, -cos yaw cos pitch), and the position is
    the target walked back along it.
    """
    yaw, pitch = math.radians(yaw), math.radians(pitch)
    forward = (-math.sin(yaw) * math.cos(pitch),
               math.sin(pitch),
               -math.cos(yaw) * math.cos(pitch))
    return (tuple(target[i] - forward[i] * distance for i in range(3)),
            (pitch, yaw, 0.0))


# --- the scene ----------------------------------------------------------------

def build(profiles, profile_paths, mat, prop, tex, curve):
    s = Scene()

    # --- the camera and its shots --------------------------------------------
    start, start_rotation = look_at(*SHOTS[0][1:])
    profile = profiles[focus_band(SHOTS[0][2])]

    s.entity("Camp Camera", position=start, rotation=start_rotation)
    s.block("CameraComponent", [
        ("ViewRank", 0), ("FixedAspectRatio", "false"),
        ("ProjectionType", "Perspective"), ("PerspectiveFOV", 50),
        ("PerspectiveNearClip", 0.05), ("PerspectiveFarClip", 400),
        ("OrthographicScale", 10), ("OrthographicNearClip", -1),
        ("OrthographicFarClip", 1),
        ("PostProfile", profile),
    ])
    # Slow. A travel of under four seconds reads as a whip-pan between
    # postcards; at eleven it reads as a camera being carried, and the
    # scene has time to be looked at rather than swept past.
    # **Back to the defaults.** The pacing was slowed three times on request
    # and each step was applied to the already-slowed value rather than to the
    # original, so it compounded: 4.2 s of travel became 11.4, then 24, then
    # 12.7, and every one of those was still slower than the shot before it.
    # 3.4 and 4.2 are what the camera was written with.
    #
    # The focus table rides on the script rather than on twelve markers: one
    # profile *path* per shot, in shot order, comma separated. Written from the
    # same `focus_band` call the profiles themselves were built from, so a band
    # cannot be renumbered here and left stale there.
    #
    # **A path and not a handle, which is not a detail.** The scripting bridge
    # takes an asset field as text and resolves it with Registry::GetHandle,
    # which looks a *path* up -- a handle is the engine's internal name and a
    # script holding one could do nothing honest with it, so the getter hands
    # out paths too. Handing it a handle fails the lookup, SetComponentField
    # returns false, and the camera keeps whatever lens it started with: every
    # shot focused at the first shot's distance, silently, because a refused
    # write reports nothing to the scene.
    shot_profiles = ",".join(profile_paths[focus_band(shot[2])] for shot in SHOTS)
    s.managed_script("CampCamera", HoldSeconds=3.4, TravelSeconds=4.2,
                     Profiles=shot_profiles)

    # The shots themselves. Empty transforms, named so the script can find
    # them -- which makes the camera move a thing you can drag in the editor
    # instead of a table of numbers inside a `.cs`.
    for name, target, distance, yaw, pitch in SHOTS:
        position, rotation = look_at(target, distance, yaw, pitch)

        # **A shot is only a shot if the camera can stand there.** Solving from
        # a target and an angle is the right way to choose a framing and the
        # wrong way to notice that the answer is inside the tent -- shot 4 came
        # out standing in the fire the first time, and the sign of its yaw was
        # the only thing wrong with it. So the three things it can be inside
        # are checked here rather than found in a render.
        floor = ground_height(position[0], position[2])
        if position[1] < floor + 0.35:
            raise SystemExit(
                f"{name} is {floor + 0.35 - position[1]:.2f} m below the "
                f"ground at ({position[0]:.1f}, {position[2]:.1f})")

        # The fire is in this list for the same reason the tent is: it is a
        # solid object at the origin with a ring of stones round it, and a
        # camera inside it sees the inside of a flame.
        for what, at, radius in (("the tent", (3.05, -2.5), 2.2),
                                 ("the van", VAN_AT, 3.4),
                                 # The ring is 0.94 m out and its stones are
                                 # 0.2 m across, so 1.2 m is where the fire
                                 # physically ends. Anything larger than that
                                 # is not a collision, it is an opinion about
                                 # framing -- and it rejected the mirror
                                 # close-up, which is a good shot standing just
                                 # outside the stones.
                                 ("the fire", (0.0, 0.0), 1.2)):
            gap = math.hypot(position[0] - at[0], position[2] - at[1])
            if gap < radius:
                raise SystemExit(
                    f"{name} stands {gap:.2f} m from {what}, which is inside "
                    f"it -- move the target or flip the yaw")

        # A transform and a name, and nothing else. Where the camera stands
        # and what it looks at is all a marker is; its lens is in the table on
        # the script above.
        s.entity(name, position=position, rotation=rotation)

    # --- the ground ----------------------------------------------------------
    s.entity("Ground", position=(0, TERRAIN_Y, 0))
    s.block("TerrainComponent", [
        ("Terrain", tex["terrain"]),
        ("Size", TERRAIN_SIZE), ("Height", TERRAIN_HEIGHT),
        ("Material", mat["ground"]), ("Layer1", mat["scrub"]),
        ("Layer2", 0), ("Layer3", 0),
        ("TextureScale", 26), ("Collision", "true"),
    ])

    # --- the fire ------------------------------------------------------------
    #
    # The centre of the composition and the only real light in the scene, so
    # everything else is placed by where its light falls.

    s.entity("Fire")

    # The ring. Pale stones, and the one thing near the fire that is not warm
    # coloured -- which is what makes it read as a ring rather than as more
    # firelight.
    for i, (x, z, spin, size) in enumerate(scatter(11, 11, 0.82, 0.94)):
        s.entity(f"Ring Stone {i}", parent="Fire",
                 position=(x, ground_height(x, z) - 0.04, z),
                 rotation=(0, spin, 0),
                 scale=(0.62 * size, 0.42 * size, 0.62 * size))
        s.mesh(prop["rock"], mat["stone"])

    s.entity("Fire Logs", parent="Fire", position=(0, 0, 0))
    s.mesh(prop["fire_logs"], mat["charred"])

    # The flame is **modelled**, not simulated. A particle system alone gives a
    # soft orange smudge; the reference's fire is hard-edged, and belonging to
    # the same drawing as the trees matters more here than being convincing on
    # its own.
    s.entity("Flame", parent="Fire", position=(0, 0.16, 0))
    s.mesh(prop["flame_outer"], mat["flame_hot"])

    s.entity("Flame Core", parent="Flame", position=(0, 0.02, 0))
    s.mesh(prop["flame_inner"], mat["flame_core"])

    # Embers rising off it. This is what particles are actually good at, and
    # all that is left for them to do now the flame has a shape.
    s.entity("Embers", parent="Fire", position=(0, 0.55, 0))
    s.block("ParticleEmitterComponent", [
        # An ember off a camp fire floats rather than launches -- it is a scrap
        # of ash with more drag than weight -- and the drag and the long
        # lifetime are what make its rise decelerate. **The speed itself is
        # back where it started**: dropping it to a third as well left the
        # embers barely leaving the flame.
        ("Emit", "true"), ("Rate", 13), ("Burst", 0), ("Lifetime", 2.8),
        ("LifetimeJitter", 0.45), ("Direction", "[0, 1, 0]"), ("Spread", 28),
        ("Speed", 1.15), ("SpeedJitter", 0.6), ("Gravity", "[0.07, 0.42, 0]"),
        ("Drag", 1.2), ("SizeStart", 0.055), ("SizeEnd", 0.012),
        ("ColorStart", "[1, 0.82, 0.4, 1]"), ("ColorEnd", "[1, 0.26, 0.05, 0]"),
        ("Spin", 0.4), ("Facing", "Billboard"), ("Blend", "Additive"),
        ("Space", "World"), ("Texture", tex["spark"]), ("MaxParticles", 220),
        ("SimulateOnGpu", "false"),
        ("SizeCurve", curve["size"]), ("ColorGradient", curve["ember"]),
        ("AlphaCurve", curve["alpha"]),
    ])

    # The heat above it: a few big soft billboards, which is what carries the
    # glow the modelled shards cannot.
    s.entity("Fire Glow", parent="Fire", position=(0, 0.42, 0))
    s.block("ParticleEmitterComponent", [
        ("Emit", "true"), ("Rate", 11), ("Burst", 0), ("Lifetime", 1.2),
        ("LifetimeJitter", 0.3), ("Direction", "[0, 1, 0]"), ("Spread", 22),
        ("Speed", 0.7), ("SpeedJitter", 0.3), ("Gravity", "[0, 0.28, 0]"),
        ("Drag", 2.0), ("SizeStart", 0.5), ("SizeEnd", 0.1),
        ("ColorStart", "[1, 0.6, 0.2, 1]"), ("ColorEnd", "[0.8, 0.2, 0.03, 0]"),
        ("Spin", 0.5), ("Facing", "Billboard"), ("Blend", "Additive"),
        ("Space", "Local"), ("Texture", tex["flame"]), ("MaxParticles", 96),
        ("SimulateOnGpu", "false"),
        ("SizeCurve", curve["size"]), ("ColorGradient", curve["ember"]),
        ("AlphaCurve", curve["alpha"]),
    ])

    # And the smoke, which is the one thing here that has to be *alpha*
    # blended rather than additive. Smoke does not emit light -- it takes it
    # away, and an additive smoke plume is a column of fog lit from inside.
    #
    # World space, so a puff stays where it was born and the column leans away
    # from the fire instead of riding it. Slow, large, and long-lived: a
    # particle that grows from 30 cm to a metre and a half over four seconds is
    # what makes a fire look like it is burning wood rather than gas.
    s.entity("Smoke", parent="Fire", position=(0, 0.95, 0))
    s.block("ParticleEmitterComponent", [
        # **Faint.** The first pass put a pale column up the middle of four of
        # the five shots, brighter in places than the fire it came off -- which
        # inverts the whole composition, because the brightest thing in frame
        # is supposed to be the fire and nothing else. Smoke at night is
        # something you notice second.
        ("Emit", "true"), ("Rate", 4), ("Burst", 0), ("Lifetime", 5.5),
        ("LifetimeJitter", 0.4), ("Direction", "[0, 1, 0]"), ("Spread", 16),
        # Restored with the embers and the glow, and slower than both -- smoke
        # that leaves a fire faster than the sparks in it is smoke off a
        # different fire.
        ("Speed", 0.5), ("SpeedJitter", 0.3), ("Gravity", "[0.12, 0.2, 0.04]"),
        ("Drag", 0.55), ("SizeStart", 0.3), ("SizeEnd", 1.3),
        ("ColorStart", "[0.15, 0.14, 0.16, 0.12]"),
        ("ColorEnd", "[0.08, 0.08, 0.11, 0]"),
        ("Spin", 0.22), ("Facing", "Billboard"), ("Blend", "Alpha"),
        ("Space", "World"), ("Texture", tex["flame"]), ("MaxParticles", 72),
        ("SimulateOnGpu", "false"),
        ("SizeCurve", 0), ("ColorGradient", 0), ("AlphaCurve", curve["alpha"]),
    ])

    # **The range is the composition.** At nine metres the pool of light ends
    # at the chairs and the treeline stays dark, which is the picture. At
    # eighteen it reached the trees and there was no falloff anywhere in frame.
    s.entity("Fire Light", parent="Fire", position=(0, 0.5, 0))
