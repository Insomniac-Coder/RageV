    # And the one control. Red on near-black, which is the house accent and
    # the one cool thing in a warm frame, so it stays legible over any part of
    # it.
    #
    # The button *names a method on another entity* rather than carrying a
    # script of its own -- `OnClickTarget` plus `OnClickMethod` -- because the
    # thing being paused is the camera, and the camera is where the state
    # lives. A button with its own copy of "am I paused" is a second source of
    # truth for one bool.
    rect("Pause Button", "HUD", (0.5, 1), (0.5, 1), (-96, -150), (96, -90),
         order=1, blocks=True)
    s.block("UIImageComponent", [("Texture", 0), ("Color", "[0.16, 0.06, 0.07, 0.85]")])
    s.block("UIButtonComponent", [
        ("Interactable", "true"), ("NormalColor", "[0.78, 0.78, 0.8, 1]"),
        ("HoverColor", "[1, 1, 1, 1]"), ("PressedColor", "[0.45, 0.45, 0.5, 1]"),
        ("OnClickTarget", handle_for("Camp Camera")),
        ("OnClickMethod", "TogglePause"),
    ])
    label("Pause Label", "Pause Button", "pause", 24, "[0.92, 0.35, 0.36, 1]",
          order=2, inset=(10, 10))

    # --- what it sounds like -------------------------------------------------
    #
    # A wind bed with crickets in it, seamless by construction and generated by
    # `make_ambience.py`. **Not spatial**: an ambience has no position, and
    # giving it one means the wood goes quiet when the camera walks away from a
    # point in the middle of it. The fire is the spatial one, and the contrast
    # between the two is the point -- the fire arrives as you approach it, and
    # the wood is simply always there.
    s.entity("Night Ambience", position=(0, 2.0, 0))
    s.block("AudioSourceComponent", [
        ("Clip", tex["ambience"]), ("Bus", "SFX"), ("Volume", 0.11),
        ("Pitch", 1), ("Loop", "true"), ("PlayOnAwake", "true"),
        ("Stream", "false"), ("Spatial", "false"), ("MinDistance", 1),
        ("MaxDistance", 200),
    ])

    return s.text()


