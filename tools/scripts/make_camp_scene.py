"""Build the camp scene: a forest clearing at night, and a camera that shows it.

    python tools/scripts/make_camp_textures.py
    python tools/scripts/make_camp_models.py
    python tools/scripts/check_models.py
    python tools/scripts/make_camp_scene.py

**The place.** A clearing in a pine forest, well after sunset. A ridge tent
pitched on the flat ground at one side. A fire burning down inside a ring of
stones, with the wood for it stacked beside. Folding chairs facing it, one
pushed back. A fallen trunk somebody has been sitting on. A case, a bedroll and
a pack. A mirror on its kickstand, angled at the fire. A fox at the treeline and
three rabbits that have come closer than they should have.

Everything below is in that description, and the description is the argument for
it. The rule the courtyard scene set holds here: **nothing goes in because it is
new -- it goes in because the place would have one.**

| The clearing has | Which exercises |
|---|---|
| Sculpted ground | Terrain: heightfield, layered materials, LOD chunks |
| A hundred pines, stones and tufts | FBX import, and instanced draws -- one mesh, many entities |
| A tent, chairs, a case, a cooler | More FBX, and the flat-shaded low-poly look |
| A fox at the treeline | glTF import, skinning, an animation clip |
| A mirror on a kickstand | A realtime probe, screen-space reflections and traced ones |
| A fire | Modelled flame, additive embers, a light that flickers, looping audio |
| Night | A dark sky, a moon, a dusk rim behind the trees, and post that earns it |
| A camera that moves | Five framed shots as entities, and a script that eases between them |

**Composition, since it is the actual subject.** The reference is a photograph
of a model, and what makes it work is four things a bright scene cannot have:

  * **One focal point, and it is the brightest thing.** The fire. Nothing else
    in the frame comes near it in value.
  * **Value separates depth.** Dark foreground, lit camp, dark treeline against
    a slightly lighter sky. Three bands the eye reads as distance -- and the
    first version had all three at the same brightness, which is why it read
    flat.
  * **The frame is framed.** Big trees at the edges, nearer and darker.
  * **Lines lead in.** The log points at the fire, the chairs face it, the
    forks reach into it.

**The light's range matters more than its intensity.** A light whose reach
exceeds the scene has no falloff inside the frame, and falloff is what makes a
fire look like a fire rather than a floodlight with a warm gel. The fire here
reaches nine metres, which ends at the chairs and leaves the treeline dark.

**Nothing here is borrowed from the courtyard.** Its own maps, its own flame
sprite, its own grade, its own curves, its own fire loop -- all generated by
`make_camp_textures.py` and by this file. The single exception is the fox,
which is the only rigged and animated asset the project has and is low-poly
already; it keeps its own glTF material and texture.
"""

