# --- handles ------------------------------------------------------------------
#
# Read from the `.meta` files the registry minted, never pasted. This scene is
# regenerated every time a model changes, and a table of handles copied by hand
# is a table that goes stale exactly when it matters.

def read_handle(path):
    path = pathlib.Path(path)
    if not path.exists():
        return None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("Handle:"):
            return int(line.split(":", 1)[1].strip())
    return None


def handles_in(directory, suffix, strip):
    found = {}
    for meta in sorted(pathlib.Path(directory).glob("*" + suffix + ".meta")):
        handle = read_handle(meta)
        if handle:
            found[meta.name[:-len(suffix) - len(".meta")].replace(strip, "", 1)] = handle
    return found


def require(table, *names):
    missing = [name for name in names if name not in table]
    if missing:
        raise SystemExit(
            "no handle yet for: " + ", ".join(missing) + "\n"
            "Run the generators, then the engine once so the registry mints "
            "them, then this again.")


# --- the ground ---------------------------------------------------------------

_HEIGHTS = None


def ground_height(x, z):
    """The clearing's surface at a world point, in metres.

    **Props are placed on the ground rather than at zero.** The clearing is
    level for sixteen metres and then lifts, so a tree at twenty metres placed
    at y = 0 is buried half a metre and one at thirty is buried two. Sampling
    the same heightfield the terrain asset was written from is the only way for
    the two to agree; guessing an offset per ring is how a forest ends up
    standing on a staircase.
    """
    global _HEIGHTS
    if _HEIGHTS is None:
        _HEIGHTS = make_terrain.clearing()

    size = _HEIGHTS.shape[0]
    u = (x / TERRAIN_SIZE + 0.5) * (size - 1)
    v = (z / TERRAIN_SIZE + 0.5) * (size - 1)

    u = min(max(u, 0.0), size - 1.001)
    v = min(max(v, 0.0), size - 1.001)

    x0, z0 = int(u), int(v)
    fx, fz = u - x0, v - z0

    def at(row, col):
        return _HEIGHTS[row, col] / 65535.0

    top = at(z0, x0) * (1 - fx) + at(z0, x0 + 1) * fx
    bottom = at(z0 + 1, x0) * (1 - fx) + at(z0 + 1, x0 + 1) * fx
    unit = top * (1 - fz) + bottom * fz

    return TERRAIN_Y + unit * TERRAIN_HEIGHT


def scatter(seed, count, inner, outer):
    """Points in a ring, from a fixed sequence.

    A hash rather than `random`: the scene has to regenerate identically or
    every run is a diff, and a seeded generator whose implementation can change
    between Python versions is not a guarantee.

    The radius is spread by its square root, so the points are even per unit of
    *area* rather than per unit of radius -- without it everything bunches at
    the inner edge, which is what a ring of trees must not do.
    """
    points = []
    for i in range(count):
        h = (seed * 6364136223846793005 + i * 1442695040888963407) & 0xFFFFFFFF
        angle = (h % 10000) / 10000.0 * math.tau
        spread = ((h >> 13) % 10000) / 10000.0
        radius = math.sqrt(inner * inner + spread * (outer * outer - inner * inner))
        spin = ((h >> 7) % 10000) / 10000.0 * math.tau
        size = 0.78 + ((h >> 19) % 10000) / 10000.0 * 0.55
        points.append((math.cos(angle) * radius, math.sin(angle) * radius,
                       spin, size))
    return points


