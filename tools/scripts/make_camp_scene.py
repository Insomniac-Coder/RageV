    #
    # Screen space, and deliberately *not* diegetic: this is the engine talking
    # about itself, so it does not pretend to be part of the clearing. Two
    # things only -- what this is, and the one control a person watching a
    # cinematic actually wants, which is to stop it on a frame they liked.
    #
    # **The canvas origin is the top-left and Y grows downward**, so a band at
    # the bottom of the screen anchors at y = 1 with *negative* offsets. Getting
