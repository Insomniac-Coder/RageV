#
# Five shots, each written as a target, a distance and two angles -- which is
# how a shot is actually chosen -- and solved into a position here. A position
# and an euler triple typed in directly is a number nobody can adjust, because
# moving the camera closer means recomputing all three.
#
# The shots go into the scene as entities the script reads, so they are visible
# and movable in the editor rather than compiled into a script.

# (name, target, distance, yaw degrees, pitch degrees)
#
# Twelve, and the order is the film. Consecutive shots that share a target and a
# distance and differ only in yaw give a **lateral move**: the script eases
